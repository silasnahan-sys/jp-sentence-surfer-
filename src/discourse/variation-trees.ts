/**
 * Variation Tree System (バリエーション・ツリー)
 *
 * Defines canonical stem forms and all known surface variations for 30+
 * major Japanese discourse grammar construction families, optimised for
 * spoken language and YT-transcript text.
 *
 * Each VariationTree has:
 *   stem            — the canonical/base form used as an index key
 *   familyName      — human-readable JP label for the family
 *   variations      — ordered list of VariationNodes (base → most elaborated)
 *   functionDescription — what the construction expresses
 */

import { VariationTree, VariationNode } from '../types';

// ─── Helper ───────────────────────────────────────────────────────────────────

function v(
    surface: string,
    morphemes: string[],
    additions: string[],
    nuanceShift: string,
    register: VariationNode['register'],
    spokenFrequency: VariationNode['spokenFrequency'],
    parentVariation?: string,
): VariationNode {
    return { surface, morphemes, additions, nuanceShift, register, spokenFrequency, parentVariation };
}

