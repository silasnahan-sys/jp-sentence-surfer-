/** Index: stem → VariationTree */
export const VARIATION_TREE_BY_STEM = new Map<string, VariationTree>(
    ALL_VARIATION_TREES.map(t => [t.stem, t])
);

/** Index: surface → { tree, node } */
export const VARIATION_BY_SURFACE = new Map<string, { tree: VariationTree; node: VariationNode }>();
for (const tree of ALL_VARIATION_TREES) {
    for (const node of tree.variations) {
        VARIATION_BY_SURFACE.set(node.surface, { tree, node });
    }
}

/**
 * Find which stem family a given surface form belongs to.
 * Returns null if no match found.
 */
export function findStemFamily(surface: string): VariationTree | null {
    const hit = VARIATION_BY_SURFACE.get(surface);
    if (hit) return hit.tree;
    // Partial match: check if any tree variation surface is a substring
    for (const [s, hit2] of VARIATION_BY_SURFACE) {
        if (surface.includes(s) || s.includes(surface)) {
            return hit2.tree;
        }
    }
    return null;
}

/**
 * Get all surface forms (across all trees) that could match a text fragment.
 */
export function getAllSurfaces(): string[] {
    return Array.from(VARIATION_BY_SURFACE.keys());
}

/**
 * Get occurrence count display label.
 */
export function variationLabel(node: VariationNode): string {
    const regLabel: Record<VariationNode['register'], string> = {
        formal:  '敬体',
        neutral: '普通',
        casual:  '口語',
        rough:   '荒語',
    };
    const freqLabel: Record<VariationNode['spokenFrequency'], string> = {
        high:   '★★★',
        medium: '★★',
        low:    '★',
        rare:   '☆',
    };
    return `${node.surface} [${regLabel[node.register]} ${freqLabel[node.spokenFrequency]}]`;
}
